#!/usr/bin/env python3
"""Build the layered iOS 26+ app icon (Icon Composer `.icon` package) for HealthyPaw.

Writes assets/brand/ios/AppIcon.icon/{icon.json, Assets/*.svg}.

The paw is drawn once, white, on a 1024 x 1024 canvas, square and unmasked
(iOS applies the rounded mask and the Liquid Glass effects). The daily tick is
cut out of the pad, so whatever sits behind the paw shows through it in every
appearance: orange in default, navy in dark, glass in clear, the tint in tinted.

Appearances (Apple HIG, app icons):
  default      orange ground, white paw
  dark         navy ground, orange paw        (fill specializations below)
  clear/tinted generated by iOS from the same layers

Needs: python3, shapely (pip install shapely).
Run from the repo root: python3 assets/brand/scripts/make_ios_app_icon.py
"""
from __future__ import annotations

import json
from pathlib import Path

from shapely.geometry import LineString

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "ios" / "AppIcon.icon"

ORANGE = (0xFF, 0x8A, 0x4C)
NAVY = (0x1E, 0x1B, 0x3A)
WHITE = (0xFF, 0xFF, 0xFF)

# Geometry from svg/icon-ios.svg (unchanged from the chosen "Tick paw" logo).
TOES = [
    (300, 420, 72, 92, -22),
    (430, 300, 76, 98, -8),
    (594, 300, 76, 98, 8),
    (724, 420, 72, 92, 22),
]
PAD = ("M512 470c-120 0-250 130-250 240 0 70 50 110 120 110 50 0 85-25 130-25"
       "s80 25 130 25c70 0 120-40 120-110 0-110-130-240-250-240z")
TICK = [(418, 668), (484, 730), (612, 594)]
TICK_WIDTH = 44


def srgb(rgb: tuple[int, int, int]) -> str:
    return "srgb:" + ",".join(f"{c / 255:.5f}" for c in rgb) + ",1.00000"


def tick_outline_path() -> str:
    """The tick stroke (round caps and join) as a closed outline path."""
    poly = LineString(TICK).buffer(TICK_WIDTH / 2, quad_segs=24, cap_style="round", join_style="round")
    pts = list(poly.exterior.coords)[:-1]
    # Reverse the winding against the pad so the hole works with either fill rule.
    pts.reverse()
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


def svg(body: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
        f"{body}</svg>\n"
    )


def toes_svg() -> str:
    shapes = "".join(
        f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" transform="rotate({a} {cx} {cy})"/>'
        for cx, cy, rx, ry, a in TOES
    )
    return svg(f'<g fill="#FFFFFF">{shapes}</g>')


def pad_svg() -> str:
    return svg(f'<path fill="#FFFFFF" fill-rule="evenodd" d="{PAD} {tick_outline_path()}"/>')


def icon_json() -> dict:
    paw_fill = [
        {"value": {"solid": srgb(WHITE)}},
        {"appearance": "dark", "value": {"solid": srgb(ORANGE)}},
    ]
    return {
        "fill-specializations": [
            {"value": {"solid": srgb(ORANGE)}},
            {"appearance": "dark", "value": {"solid": srgb(NAVY)}},
        ],
        "groups": [
            {
                "name": "Paw",
                "layers": [
                    {"name": "Pad", "image-name": "pad.svg", "glass": True, "fill-specializations": paw_fill},
                    {"name": "Toes", "image-name": "toes.svg", "glass": True, "fill-specializations": paw_fill},
                ],
                "shadow": {"kind": "neutral", "opacity": 0.5},
                "translucency": {"enabled": True, "value": 0.5},
            }
        ],
        "supported-platforms": {"squares": "shared"},
    }


def main() -> None:
    assets = OUT / "Assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "pad.svg").write_text(pad_svg())
    (assets / "toes.svg").write_text(toes_svg())
    (OUT / "icon.json").write_text(json.dumps(icon_json(), indent=2, sort_keys=True) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
