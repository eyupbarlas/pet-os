#!/usr/bin/env bash
# Regenerates supabase/all-migrations.sql (one paste-able file) from the migrations.
cd "$(dirname "$0")/.."
{ echo "-- GENERATED by scripts/build-setup-sql.sh from supabase/migrations/*.sql. Paste into the Supabase SQL editor on a NEW project."
  for f in supabase/migrations/*.sql; do echo; echo "-- ===== $f ====="; cat "$f"; done; } > supabase/all-migrations.sql
